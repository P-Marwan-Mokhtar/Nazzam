// السياق: كان الـService Worker الأساسي مسجَّل على نطاق (scope) الجذر "/" قبل
// ما ننقل التطبيق كله لمجلد /app/. المتصفحات اللي عندها الجهاز مسجَّل بالنطاق
// القديم مش هتلاحظ النقل تلقائيًا، وهتفضل تحاول تستخدم منطق قديم بيدور على
// ملفات في أماكنها القديمة اللي مبقتش موجودة — وده اللي بيكسر العمل أوفلاين.
//
// الملف ده بيحل المشكلة دي: يمسح كل الكاش القديم، يفك تسجيل نفسه بنفسه، ويجبر
// أي صفحة مفتوحة تعمل reload — فبمجرد ما أي جهاز عنده النسخة القديمة يفتح
// الموقع وهو أونلاين (ولو مرة واحدة بس)، بينضف تلقائيًا من غير أي تدخل من المستخدم.
// النطاق الحقيقي للتطبيق دلوقتي بقى /app/sw.js، وده الملف الوحيد المفروض
// يتحدّث أو يتعدّل مستقبلًا لأي تغييرات فعلية في التخزين المؤقت.

self.addEventListener('install', () => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      // نمسح كل الكاش القديم المخزّن تحت النطاق ده
      const keys = await caches.keys();
      await Promise.all(keys.map((key) => caches.delete(key)));

      // نفك تسجيل الـService Worker القديم ده نهائيًا
      await self.registration.unregister();

      // نجبر أي تبويب مفتوح حاليًا يعمل reload عشان ياخد الصفحة الجديدة نظيفة
      const clientsList = await self.clients.matchAll({ type: 'window' });
      clientsList.forEach((client) => client.navigate(client.url));
    })()
  );
});
