function tr(lang, key) {
  const d = STRINGS[lang] || STRINGS.ar;
  return d[key] !== undefined ? d[key] : (STRINGS.ar[key] !== undefined ? STRINGS.ar[key] : key);
}

export function tLanding(key) {
  return tr(getLandingLang(), key);
}

// يطبّق اللغة على الصفحة: الاتجاه + كل عناصر data-lp + العنوان والوصف.
export function applyLandingLang(lang) {
  const L = lang === 'en' ? 'en' : 'ar';
  document.documentElement.lang = L;
  document.documentElement.dir = L === 'ar' ? 'rtl' : 'ltr';
  const year = new Date().getFullYear();
  const pick = (k) => tr(L, k).replace('{y}', String(year));
  document.querySelectorAll('[data-lp]').forEach((el) => { el.textContent = pick(el.dataset.lp); });
  document.querySelectorAll('[data-lp-html]').forEach((el) => { el.innerHTML = pick(el.dataset.lpHtml); });
  document.querySelectorAll('[data-lp-alt]').forEach((el) => { el.setAttribute('alt', pick(el.dataset.lpAlt)); });
  document.querySelectorAll('[data-lp-aria]').forEach((el) => { el.setAttribute('aria-label', pick(el.dataset.lpAria)); });
  document.querySelectorAll('[data-lp-title]').forEach((el) => { el.setAttribute('title', pick(el.dataset.lpTitle)); });
  document.title = pick(document.documentElement.dataset.lpTitle || 'meta.title');
  const descKey = document.documentElement.dataset.lpDesc || 'meta.desc';
  const md = document.querySelector('meta[name="description"]');
  if (md) md.setAttribute('content', pick(descKey));
  const ogd = document.querySelector('meta[property="og:description"]');
  if (ogd) ogd.setAttribute('content', pick(descKey));
  const ogt = document.querySelector('meta[property="og:title"]');
  if (ogt) ogt.setAttribute('content', pick(document.documentElement.dataset.lpTitle || 'meta.title'));
  // زرار اللغة أيقونة كوكب (بلا نص) — نحدّث خصائص الوصول فقط
  document.querySelectorAll('.lp-lang-btn').forEach((b) => {
    b.setAttribute('aria-label', pick('nav.lang'));
    b.setAttribute('title', pick('nav.lang'));
  });
  const lpYear = document.getElementById('lpYear');
  if (lpYear) lpYear.textContent = String(year);
}

// تبديل اللغة: حفظ + إعادة تحميل (يضمن ترجمة العناصر المولّدة بالـ JS أيضًا).
export function toggleLandingLang() {
  const next = getLandingLang() === 'ar' ? 'en' : 'ar';
  try {
    localStorage.setItem(LANDING_LANG_KEY, next);
    sessionStorage.setItem('lp-scroll', String(window.scrollY || 0));
  } catch (e) {}
  window.location.reload();
}

// استعادة موضع السكرول بعد تبديل اللغة بالريلود.
export function restoreLandingScroll() {
  try {
    const y = sessionStorage.getItem('lp-scroll');
    if (y !== null) {
      sessionStorage.removeItem('lp-scroll');
      window.scrollTo(0, parseInt(y, 10) || 0);
    }
  } catch (e) {}
}
