export const LANDING_LANG_KEY = 'nazam-lang';

export function getLandingLang() {
  try {
    const s = localStorage.getItem(LANDING_LANG_KEY);
    if (s === 'ar' || s === 'en') return s;
  } catch (e) {}
  try {
    if ((navigator.language || '').slice(0, 2).toLowerCase() === 'en') return 'en';
  } catch (e) {}
  return 'ar';
}

