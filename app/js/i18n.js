import { state } from './state.js';
import { DAY_NAMES, SHORT_DAY_NAMES, MONTH_NAMES } from './utils.js';

let currentLang = 'ar';

export function getLang(){ return currentLang; }

export function setLang(lang){
  currentLang = lang;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  try { localStorage.setItem('nazam-lang', lang); } catch(e){}
  state.lang = lang;
  // تحديث أسماء الأيام والأشهر
  const dn = lang === 'en' ? DAY_NAMES_EN : DAY_NAMES_AR;
  const sdn = lang === 'en' ? SHORT_DAY_NAMES_EN : SHORT_DAY_NAMES_AR;
  const mn = lang === 'en' ? MONTH_NAMES_EN : MONTH_NAMES_AR;
  DAY_NAMES.length = 0; DAY_NAMES.push(...dn);
  SHORT_DAY_NAMES.length = 0; SHORT_DAY_NAMES.push(...sdn);
  MONTH_NAMES.length = 0; MONTH_NAMES.push(...mn);
}

export function initLang(){
  try {
    const saved = localStorage.getItem('nazam-lang');
    if(saved === 'ar' || saved === 'en') currentLang = saved;
    else {
      // أول زيارة: نستخدم لغة المتصفح
      const browserLang = (navigator.language || '').slice(0, 2).toLowerCase();
      if(browserLang === 'en') currentLang = 'en';
      else currentLang = 'ar';
    }
  } catch(e){}
  document.documentElement.lang = currentLang;
  document.documentElement.dir = currentLang === 'ar' ? 'rtl' : 'ltr';
  state.lang = currentLang;
  // تحديث أسماء الأيام والأشهر
  const dn = currentLang === 'en' ? DAY_NAMES_EN : DAY_NAMES_AR;
  const sdn = currentLang === 'en' ? SHORT_DAY_NAMES_EN : SHORT_DAY_NAMES_AR;
  const mn = currentLang === 'en' ? MONTH_NAMES_EN : MONTH_NAMES_AR;
  DAY_NAMES.length = 0; DAY_NAMES.push(...dn);
  SHORT_DAY_NAMES.length = 0; SHORT_DAY_NAMES.push(...sdn);
  MONTH_NAMES.length = 0; MONTH_NAMES.push(...mn);
}

// ---- Translation lookup ----
export function t(key, params){
  const val = (T[currentLang] || T.ar)[key] || T.ar[key] || key;
  if(!params) return val;
  return val.replace(/\{(\w+)\}/g, (_, k) => params[k] !== undefined ? params[k] : `{${k}}`);
}

// ---- Plural helper ----
export function pl(count, singular, plural){
  if(currentLang === 'en') return count === 1 ? singular : plural;
  return count === 1 ? singular : plural;
}

// ---- Time formatting (language-aware) ----
export function formatHM(ms){
  const totalMin = Math.round(ms / 60000);
  const h = Math.floor(totalMin / 60);
  const m = totalMin % 60;
  if(currentLang === 'en'){
    if(h > 0 && m > 0) return `${h}h ${m}m`;
    if(h > 0) return `${h}h`;
    if(m > 0) return `${m}m`;
    return '0m';
  }
  if(h > 0 && m > 0) return `${h} س ${m} د`;
  if(h > 0) return `${h} ساعة`;
  if(m > 0) return `${m} دقيقة`;
  return '0 د';
}

export function formatMinutes(totalMinutes){
  if(!totalMinutes || totalMinutes <= 0) return '';
  const hours = Math.floor(totalMinutes / 60);
  const mins = Math.round(totalMinutes % 60);
  if(currentLang === 'en'){
    if(hours > 0 && mins > 0) return `${hours} hour${hours>1?'s':''} and ${mins} minute${mins>1?'s':''}`;
    if(hours > 0) return `${hours} hour${hours>1?'s':''}`;
    return `${mins} minute${mins>1?'s':''}`;
  }
  if(hours > 0 && mins > 0) return `${hours} ${hours === 1 ? 'ساعة' : 'ساعات'} و ${mins} دقيقة`;
  if(hours > 0) return `${hours} ${hours === 1 ? 'ساعة' : 'ساعات'}`;
  return `${mins} دقيقة`;
}

